/**
 * CREDITS.md, generated from the compiled content (NFR-08, CR-11): every external asset the game serves and the stock
 * voices. It depends only on assets-src/manifest.yaml and content/voices.yaml, so writing text never changes it and
 * two sessions cannot collide on it. Written by `npm run content`; never edit it by hand.
 */
import type { Content, CreditC } from '../src/content/schema.ts';

const list = (rows: CreditC[]) => rows.map((c) => `- ${c.page ? `[${c.title}](${c.page})` : c.title} · ${c.credit} · ${c.license} · \`${c.file}\``).join('\n');

export function creditsMarkdown(content: Content): string {
  const c = content.credits;
  return [
    '# Credits',
    '',
    'Generated by `npm run content` from `assets-src/manifest.yaml` and `content/voices.yaml`. Do not edit by hand.',
    '',
    'Data & imagery: NASA. This project is not affiliated with or endorsed by NASA. No NASA logo is used.',
    '',
    '## 3D models',
    '',
    list(c.models),
    '',
    '## Photographs',
    '',
    list(c.images),
    '',
    '## Textures',
    '',
    list(c.textures),
    '',
    '## Software served with the game',
    '',
    list(c.code),
    '',
    '## Voices (AI-generated)',
    '',
    `Every voice is generated by text to speech (ElevenLabs) with stock voices of adult voice actors: ${c.voices.map((v) => `${v.name} (${v.role})`).join(', ')}.`,
    'No voice imitates a real person; the words of real people are shown as text. Every voice file carries the tag "AI-generated voice (ElevenLabs)".',
    '',
    '## Typefaces and libraries',
    '',
    'Cinzel, Atkinson Hyperlegible, IBM Plex Mono and Cormorant Garamond (SIL Open Font License). three.js, React and Zustand (MIT License).',
    'Music and sound effects are synthesized by the game itself.',
    '',
    '## Sources of the facts',
    '',
    'Every fact carries its own source link, in the game and in `content/`. They are not repeated here.',
    '',
  ].join('\n');
}
